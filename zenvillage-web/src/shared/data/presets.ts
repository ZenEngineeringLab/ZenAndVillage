export function buildPresetCSS(preset: Preset): string {
  const rootVars = Object.entries(preset.light)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')
  const darkVars = Object.entries(preset.dark)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')
  return `:root {\n${rootVars}\n}\n.dark {\n${darkVars}\n}`
}
